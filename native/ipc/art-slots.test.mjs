import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, mkdir, writeFile, access } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
import { ART_SLOT_COUNT, prepareArtSlots, familiarAnimationFile, familiarSheetFile } from './art-slots.mjs';
import { makeSpriteSheet } from '../../bridge/runtime.mjs';

test('prepare writes 128 familiar animation slots without replacing an existing sheet', async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'isaac-anim-'));
  const portraits = path.join(directory, 'resources', 'gfx', 'items', 'collectibles');
  await mkdir(portraits, { recursive: true });
  await sharp({ create: { width: 32, height: 32, channels: 4, background: 'transparent' } }).png().toFile(path.join(portraits, 'ember_orb.png'));
  await prepareArtSlots(directory);
  const familiarDirectory = path.join(directory, 'resources', 'gfx', 'familiars');
  await access(path.join(familiarDirectory, 'generated_familiar_blank.anm2'));
  const blank = await sharp(path.join(familiarDirectory, 'generated_familiar_blank.png')).metadata();
  assert.equal(blank.width, 256);
  assert.equal(blank.height, 32);
  const kept = path.join(familiarDirectory, familiarSheetFile(7));
  await writeFile(kept, Buffer.from('kept-sheet'));
  await prepareArtSlots(directory);
  assert.equal(await readFile(kept, 'utf8'), 'kept-sheet');
  const animation = await readFile(path.join(familiarDirectory, familiarAnimationFile(63)), 'utf8');
  assert.match(animation, /Name="Idle"/);
  assert.match(animation, /Name="Float"/);
  assert.match(animation, /Name="Hop"/);
  assert.match(animation, /Name="Spin"/);
  assert.match(animation, /<Nulls\/>/);
  assert.match(animation, /<Events\/>/);
  assert.match(animation, /familiars\/generated_familiar_sheet_63\.png/);
  assert.match(animation, /XScale="200"/);
  assert.ok(animation.split(/\r?\n/).every((line) => line.length < 400));
  assert.equal(ART_SLOT_COUNT, 128);
  const source = await sharp({ create: { width: 64, height: 64, channels: 4, background: 'white' } }).png().toBuffer();
  const sheet = await sharp(await makeSpriteSheet(source)).metadata();
  assert.equal(sheet.width, 256);
  assert.equal(sheet.height, 32);
});
